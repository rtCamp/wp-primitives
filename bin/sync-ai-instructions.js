#! /usr/bin/env node

/* eslint no-console: 0 */

/**
 * Sync AI and Copilot instructions for rtCamp WordPress projects.
 *
 * Run from a package that requires rtcamp/wp-primitives with `npm run sync-ai` (also called by `npm run init`).
 *
 *   1. Refresh: copy vendor/rtcamp/wp-primitives/ai/primitives-php.instructions.md into the
 *      package's .github/instructions/.
 *   2. Project: if the package is inside a wp-content root (an ancestor containing plugins/),
 *      write every package's instructions to the root's .github/instructions/, with applyTo
 *      globs rewritten relative to the root. Rules shared by several packages go to one file.
 *
 * A standalone plugin or theme repository runs step 1 only.
 *
 * --check: write nothing, and exit 1 if any file is out of date.
 * --root DIR: search for the wp-content root from DIR instead of the working directory.
 *
 * @see docs/ai-review-system.md
 */

const fs = require( 'fs' );
const path = require( 'path' );

const PACKAGE_DIRS = [ 'plugins', 'themes' ];
const FRAMEWORK_SRC =
	'vendor/rtcamp/wp-primitives/ai/primitives-php.instructions.md';
const MARKER =
	'<!-- GENERATED by rtcamp/wp-primitives; edit the source, not here. -->';

// Delete the legacy instruction file generated by rtcamp/wp-framework.
const LEGACY_INSTRUCTION_FILE = 'framework-php.instructions.md';
const LEGACY_MARKER =
	'<!-- GENERATED by rtcamp/wp-framework; edit the source, not here. -->';

// Copilot code review reads only the first 4000 characters of an instruction file.
const COPILOT_CHAR_LIMIT = 4000;

const argv = process.argv.slice( 2 );
const isCheck = argv.includes( '--check' );
const rootIdx = argv.indexOf( '--root' );

const color = {
	red: ( m ) => `\x1b[31m${ m }\x1b[0m`,
	green: ( m ) => `\x1b[32m${ m }\x1b[0m`,
	yellow: ( m ) => `\x1b[33m${ m }\x1b[0m`,
	blue: ( m ) => `\x1b[34m${ m }\x1b[0m`,
};

const log = [];
let drift = false;

/**
 * Walk up from `start` to the first ancestor containing a `plugins/` dir.
 *
 * @param {string} start Directory to start from.
 * @return {string|null} The wp-content root, or null when none is found.
 */
const findRoot = ( start ) => {
	let dir = start;
	for (;;) {
		if ( fs.existsSync( path.join( dir, 'plugins' ) ) ) {
			return dir;
		}
		const parent = path.dirname( dir );
		if ( parent === dir ) {
			return null;
		}
		dir = parent;
	}
};

/**
 * Find every package shipping path-scoped instructions under the root.
 *
 * @param {string} root wp-content root.
 * @return {Array<{type: string, slug: string, base: string, dir: string}>} packages
 */
const discoverPackages = ( root ) => {
	const found = [];
	PACKAGE_DIRS.forEach( ( type ) => {
		const container = path.join( root, type );
		if ( ! fs.existsSync( container ) ) {
			return;
		}
		fs.readdirSync( container ).forEach( ( slug ) => {
			const base = path.join( container, slug );
			const dir = path.join( base, '.github', 'instructions' );
			// Include a package that vendors rtcamp/wp-primitives even without .github/instructions/, because
			// refreshPackage() creates that directory.
			// Site repositories often commit only the root copies, so a fresh checkout has no per-package directory.
			if (
				fs.existsSync( dir ) ||
				fs.existsSync( path.join( base, FRAMEWORK_SRC ) )
			) {
				found.push( { type, slug, base, dir } );
			}
		} );
	} );
	return found;
};

/**
 * Read the `applyTo` value out of a frontmatter block.
 *
 * @param {string} content File content.
 * @return {string} Comma-separated globs, or ''.
 */
const readApplyTo = ( content ) => {
	const m = content.match( /^applyTo:\s*(["']?)(.+?)\1\s*$/m );
	return m ? m[ 2 ] : '';
};

/**
 * Replace the `applyTo` value in a frontmatter block.
 *
 * @param {string} content File content.
 * @param {string} value   New comma-separated globs.
 * @return {string} Rewritten content.
 */
const writeApplyTo = ( content, value ) =>
	content.replace( /^(applyTo:\s*)(["']?)(.+?)\2\s*$/m, `$1"${ value }"` );

/**
 * Normalised content for grouping: everything except the applyTo value.
 *
 * @param {string} content File content.
 * @return {string} Normalised content.
 */
const normalise = ( content ) => content.replace( /^applyTo:.*$/m, 'applyTo:' );

/**
 * Drop any inherited GENERATED banner; the caller appends a fresh one.
 *
 * @param {string} content File content.
 * @return {string} Content without GENERATED banner lines.
 */
const stripBanner = ( content ) =>
	content.replace( /^<!-- GENERATED.*?-->\s*$/gm, '' ).trim() + '\n';

/**
 * Prefix each package-relative glob with `<type>/<slug>/`.
 *
 * @param {string} applyTo Comma-separated package-relative globs.
 * @param {string} prefix  `<type>/<slug>`.
 * @return {string[]} Repo-root-relative globs.
 */
const prefixGlobs = ( applyTo, prefix ) =>
	applyTo
		.split( ',' )
		.map( ( g ) => `${ prefix }/${ g.trim().replace( /^\.?\//, '' ) }` );

/**
 * Append the GENERATED marker after the rules, outside the first COPILOT_CHAR_LIMIT characters.
 *
 * @param {string} content Instruction content.
 * @return {string} Content with marker appended.
 */
const withMarker = ( content ) =>
	`${ stripBanner( content ).trimEnd() }\n\n${ MARKER }\n`;

/**
 * Write `content` to `outPath` unless unchanged; record drift and a log line.
 *
 * @param {string} outPath Absolute path to write.
 * @param {string} content Desired content.
 * @param {string} relRoot Root for the log label.
 * @param {string} verb    Label verb (create/update/refresh/prune).
 */
const writeIfChanged = ( outPath, content, relRoot, verb ) => {
	const rulesLen = content.indexOf( MARKER );
	if ( rulesLen > COPILOT_CHAR_LIMIT ) {
		console.error(
			color.yellow(
				`  WARNING ${ path.relative( relRoot, outPath ) } rules are ${ rulesLen } chars (>${ COPILOT_CHAR_LIMIT }); Copilot reads only the first ${ COPILOT_CHAR_LIMIT }. Trim the source.`
			)
		);
	}
	const current = fs.existsSync( outPath )
		? fs.readFileSync( outPath, 'utf8' )
		: null;
	if ( current === content ) {
		return;
	}
	drift = true;
	log.push(
		color.green(
			`  ${ current === null ? verb : 'update' } ${ path.relative( relRoot, outPath ) }`
		)
	);
	if ( ! isCheck ) {
		fs.mkdirSync( path.dirname( outPath ), { recursive: true } );
		fs.writeFileSync( outPath, content, 'utf8' );
	}
};

/**
 * Refresh a package's primitives-php.instructions.md from its vendored copy (step 1).
 *
 * @param {string} base    Package root.
 * @param {string} relRoot Root for log labels.
 * @return {boolean} Whether the framework source was found.
 */
const refreshPackage = ( base, relRoot ) => {
	const src = path.join( base, FRAMEWORK_SRC );
	if ( ! fs.existsSync( src ) ) {
		return false;
	}
	const dest = path.join(
		base,
		'.github',
		'instructions',
		'primitives-php.instructions.md'
	);
	writeIfChanged(
		dest,
		withMarker( fs.readFileSync( src, 'utf8' ) ),
		relRoot,
		'refresh'
	);

	// Delete the rtcamp/wp-framework copy so Copilot does not read the same rules twice.
	const legacy = path.join(
		base,
		'.github',
		'instructions',
		LEGACY_INSTRUCTION_FILE
	);
	if (
		fs.existsSync( legacy ) &&
		fs.readFileSync( legacy, 'utf8' ).includes( LEGACY_MARKER )
	) {
		drift = true;
		log.push(
			color.red( `  prune  ${ path.relative( relRoot, legacy ) }` )
		);
		if ( ! isCheck ) {
			fs.unlinkSync( legacy );
		}
	}

	return true;
};

/**
 * Project every package's instructions to the wp-content root (step 2).
 *
 * @param {string} root     wp-content root.
 * @param {Array}  packages Discovered packages.
 */
const projectToRoot = ( root, packages ) => {
	const groups = new Map();
	packages.forEach( ( { type, slug, dir } ) => {
		// Under --check, a package found through its vendored rtcamp/wp-primitives may
		// have no directory yet. refreshPackage() has already reported that as drift.
		if ( ! fs.existsSync( dir ) ) {
			return;
		}
		const prefix = `${ type }/${ slug }`;
		fs.readdirSync( dir )
			.filter( ( f ) => f.endsWith( '.instructions.md' ) )
			.forEach( ( file ) => {
				const content = stripBanner(
					fs.readFileSync( path.join( dir, file ), 'utf8' )
				);
				const key = `${ file }\0${ normalise( content ) }`;
				if ( ! groups.has( key ) ) {
					groups.set( key, { basename: file, content, members: [] } );
				}
				groups.get( key ).members.push( {
					slug,
					globs: prefixGlobs( readApplyTo( content ), prefix ),
				} );
			} );
	} );

	const outDir = path.join( root, '.github', 'instructions' );
	const outputs = {};
	for ( const { basename, content, members } of groups.values() ) {
		const allGlobs = [ ...new Set( members.flatMap( ( m ) => m.globs ) ) ];
		const outName =
			members.length > 1
				? basename
				: `${ members[ 0 ].slug }-${ basename }`;
		outputs[ outName ] = withMarker(
			writeApplyTo( content, allGlobs.join( ',' ) )
		);
	}

	Object.entries( outputs ).forEach( ( [ name, content ] ) =>
		writeIfChanged( path.join( outDir, name ), content, root, 'create' )
	);

	// Prune generated files no longer wanted.
	if ( fs.existsSync( outDir ) ) {
		const wanted = new Set( Object.keys( outputs ) );
		fs.readdirSync( outDir )
			.filter( ( f ) => {
				if ( wanted.has( f ) ) {
					return false;
				}
				const body = fs.readFileSync( path.join( outDir, f ), 'utf8' );
				return (
					body.includes( MARKER ) || body.includes( LEGACY_MARKER )
				);
			} )
			.forEach( ( f ) => {
				drift = true;
				log.push( color.red( `  prune  .github/instructions/${ f }` ) );
				if ( ! isCheck ) {
					fs.unlinkSync( path.join( outDir, f ) );
				}
			} );
	}
};

const main = () => {
	const start =
		rootIdx !== -1 ? path.resolve( argv[ rootIdx + 1 ] ) : process.cwd();
	const root = findRoot( start );

	if ( ! root ) {
		// Standalone package: refresh this package's copy only.
		if ( ! refreshPackage( start, start ) ) {
			console.log(
				color.yellow(
					'No wp-content root and no vendored rtcamp/wp-primitives found. Nothing to do.'
				)
			);
			process.exit( 0 );
		}
		console.log( color.blue( `Standalone package: ${ start }` ) );
	} else {
		const packages = discoverPackages( root );
		if ( 0 === packages.length ) {
			console.log(
				color.yellow(
					'No package under plugins/ or themes/ has .github/instructions/ or a vendored rtcamp/wp-primitives. Run `composer install` in each package, then re-run. Nothing to do.'
				)
			);
			process.exit( 0 );
		}
		packages.forEach( ( p ) => refreshPackage( p.base, root ) );
		projectToRoot( root, packages );
		console.log( color.blue( `Root: ${ root }` ) );
		console.log(
			color.blue(
				`Packages: ${ packages.map( ( p ) => `${ p.type }/${ p.slug }` ).join( ', ' ) }`
			)
		);
	}

	if ( ! drift ) {
		console.log( color.green( 'AI instructions already in sync.' ) );
		process.exit( 0 );
	}
	console.log( log.join( '\n' ) );
	if ( isCheck ) {
		console.log( color.red( '\nOut of date. Run: npm run sync-ai' ) );
		process.exit( 1 );
	}
	console.log( color.green( '\nDone.' ) );
};

main();
